import { grid } from './hand.js';

const R = (x, y, cx, cy) => Math.hypot(x + 0.5 - cx, y + 0.5 - cy);

const coffin = (inside) => (x, y) => {
  const w = y < 4 ? 2 + y : y < 6 ? 5 : 5 - Math.floor((y - 6) / 3), c = 7;
  if (y < 1 || y > 13) return null;
  const dx = Math.abs(x + 0.5 - c);
  if (dx <= w) { const edge = dx > w - 1.1 || y === 1 || y === 13; return edge ? '#' : inside(x, y) || null; }
  return null;
};

